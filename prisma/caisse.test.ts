import assert from "node:assert/strict";
import { AsyncLocalStorage } from "node:async_hooks";
import { execFileSync } from "node:child_process";
import { createHmac } from "node:crypto";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

async function main() {
  const directory = mkdtempSync(path.join(tmpdir(), "showroom-caisse-"));
  const postgres = process.env.TEST_DATABASE_URL;
  if (postgres && !/^postgres(?:ql)?:\/\/[^/]+@127\.0\.0\.1:\d+\/showroom_test(?:\?|$)/.test(postgres)) throw new Error("PostgreSQL accounting tests require an isolated loopback showroom_test database");
  process.env.DATABASE_URL = postgres || `file:${path.join(directory, "test.db")}`;
  process.env.DIRECT_URL = process.env.DATABASE_URL;
  process.env.AUTH_SECRET = "caisse-test-only";
  Object.assign(globalThis, { AsyncLocalStorage });
  if (!postgres) execFileSync(process.execPath, ["node_modules/prisma/build/index.js", "db", "push", "--skip-generate"], { env: process.env, stdio: "pipe" });
  const { prisma } = await import("../src/lib/db");
  try {
    const { workAsyncStorage } = await import("next/dist/server/app-render/work-async-storage.external");
    const { workUnitAsyncStorage } = await import("next/dist/server/app-render/work-unit-async-storage.external");
    const { RequestCookies } = await import("next/dist/server/web/spec-extension/cookies");
    const actions = await import("../src/lib/actions");
    const cashActions = await import("../src/lib/caisse-actions");
    const { cashBalance, cents } = await import("../src/lib/caisse");
    const admin = await prisma.user.create({ data: { email: "test@example.com", name: "Test", passwordHash: "unused", role: "admin" } });
    const staff = await prisma.user.create({ data: { email: "staff@example.com", name: "Staff", passwordHash: "unused", role: "staff" } });
    const form = (data: Record<string, string>) => { const f = new FormData(); Object.entries(data).forEach(([k, v]) => f.set(k, v)); return f; };
    async function request<T>(fn: () => Promise<T>, userId = admin.id, issuedAt = Date.now()) {
      const payload = `${userId}.${issuedAt}`;
      const signature = createHmac("sha256", process.env.AUTH_SECRET!).update(payload).digest("hex");
      const cookies = new RequestCookies(new Headers({ cookie: `showroom_session=${payload}.${signature}` }));
      return workAsyncStorage.run({ route: "/test", incrementalCache: {} } as any, () =>
        workUnitAsyncStorage.run({ type: "request", phase: "action", cookies, userspaceMutableCookies: cookies } as any, fn));
    }
    async function action(fn: () => Promise<unknown>, userId = admin.id) {
      await assert.rejects(request(fn, userId), (e: any) => typeof e.digest === "string" && e.digest.startsWith("NEXT_REDIRECT"));
    }
    const balance = () => prisma.$transaction(cashBalance);
    const { getSessionUser } = await import("../src/lib/auth");
    assert.equal(await request(getSessionUser, admin.id, Date.now() - 31 * 86400000), null);
    assert.equal(await request(getSessionUser, admin.id, Date.now() + 86400000), null);
    await assert.rejects(request(() => actions.saveSettingsAction(form({ showroomName: "Not allowed" })), staff.id), /Administrator/);
    await assert.rejects(request(() => actions.createUserAction(form({ email: "blocked@example.com", password: "not-allowed" })), staff.id), /Administrator/);
    await assert.rejects(request(() => actions.updateProductAction(form({ id: "1" })), 999999), /Authentication/);
    const setting = await prisma.setting.create({ data: { id: 1, showroomName: "Before", phone: "555", salePrefix: "CUSTOM-", taxRate: 7 } });
    await action(() => actions.saveSettingsAction(form({ showroomName: "After", currency: "DZD" })));
    const savedSetting = await prisma.setting.findUniqueOrThrow({ where: { id: 1 } });
    assert.equal(savedSetting.phone, setting.phone);
    assert.equal(savedSetting.salePrefix, setting.salePrefix);
    assert.equal(savedSetting.taxRate, setting.taxRate);
    const contact = await prisma.customer.create({ data: { name: "Before", phone: "555", email: "saved@example.com", notes: "Keep" } });
    await action(() => actions.saveCustomerAction(form({ id: String(contact.id), name: "After" })));
    const savedContact = await prisma.customer.findUniqueOrThrow({ where: { id: contact.id } });
    assert.equal(savedContact.phone, contact.phone);
    assert.equal(savedContact.email, contact.email);
    assert.equal(savedContact.notes, contact.notes);
    const vendor = await prisma.supplier.create({ data: { name: "Vendor", phone: "444", address: "Keep address" } });
    await action(() => actions.saveSupplierAction(form({ id: String(vendor.id), name: "Renamed vendor" })));
    assert.equal((await prisma.supplier.findUniqueOrThrow({ where: { id: vendor.id } })).address, vendor.address);
    const preservedProduct = await prisma.product.create({ data: { sku: "PRESERVE", name: "Before", description: "Keep", dimensions: "80cm", imageUrl: "/saved.png", minStock: 9, supplierId: vendor.id } });
    await action(() => actions.updateProductAction(form({ id: String(preservedProduct.id), sku: "PRESERVE", name: "After", category: "Other products", purchasePrice: "5", sellingPrice: "10" })));
    const savedProduct = await prisma.product.findUniqueOrThrow({ where: { id: preservedProduct.id } });
    for (const key of ["description", "dimensions", "imageUrl", "minStock", "supplierId"] as const) assert.equal(savedProduct[key], preservedProduct[key]);
    assert.equal(cents(12.34), 1234);
    assert.throws(() => cents(Infinity));
    const historic = await prisma.sale.create({ data: { ref: "HIST", total: 100, paid: 100 } });
    await prisma.payment.create({ data: { ref: "HIST-PAY", type: "SALE", saleId: historic.id, amount: 100 } });
    await prisma.payment.create({ data: { ref: "VOID-PAY", type: "SALE", saleId: historic.id, amount: 10, voided: true } });
    await prisma.expense.create({ data: { ref: "HIST-EXP", category: "Other", amount: 20 } });
    await assert.rejects(request(cashActions.initializeCaisseAction, staff.id), /Administrator/);
    await action(cashActions.initializeCaisseAction);
    await action(cashActions.initializeCaisseAction);
    assert.equal(await prisma.cashMovement.count(), 2);
    assert.equal(await balance(), 8000);
    await assert.rejects(request(() => actions.addPaymentAction(form({ type: "SALE", txnId: String(historic.id), amount: "1" }))), (e: any) => e.digest?.startsWith("NEXT_REDIRECT"));
    await action(cashActions.openCaisseAction);
    await assert.rejects(request(cashActions.openCaisseAction), /already open/);
    const product = await prisma.product.create({ data: { sku: "TEST", name: "Test product", stock: 10, sellingPrice: 100, purchasePrice: 50 } });
    const customerCount = await prisma.customer.count();
    await action(() => actions.createSaleAction(form({ payload: JSON.stringify({ items: [{ productId: product.id, qty: 1, unitPrice: 100 }], customerId: null, customerName: "Vente comptoir", paid: 30 }) })));
    const sale = await prisma.sale.findFirstOrThrow({ where: { ref: { not: "HIST" } } });
    assert.equal(sale.customerId, null);
    assert.equal(sale.customerName, "Vente comptoir");
    assert.equal(await prisma.customer.count(), customerCount);
    assert.equal(await balance(), 11000);
    await action(() => actions.addPaymentAction(form({ type: "SALE", txnId: String(sale.id), amount: "100" })));
    assert.equal((await prisma.sale.findUniqueOrThrow({ where: { id: sale.id } })).paid, 100);
    assert.equal(await balance(), 18000);
    const count = await prisma.cashMovement.count();
    await action(() => actions.addPaymentAction(form({ type: "SALE", txnId: String(sale.id), amount: "1" })));
    assert.equal(await prisma.cashMovement.count(), count);
    await assert.rejects(request(() => actions.addPaymentAction(form({ type: "SALE", txnId: String(sale.id), amount: "1", method: "bank transfer" }))), /Invalid cash/);
    await action(() => actions.createPurchaseAction(form({ payload: JSON.stringify({ items: [{ productId: product.id, qty: 2, unitPrice: 10 }], paid: 10 }) })));
    const purchase = await prisma.purchase.findFirstOrThrow();
    assert.equal(await balance(), 17000);
    await action(() => actions.saveExpenseAction(form({ category: "Other", amount: "5", notes: "Keep expense note", date: "2020-01-02" })));
    const expense = await prisma.expense.findFirstOrThrow({ where: { ref: { not: "HIST-EXP" } } });
    assert.equal(await balance(), 16500);
    await action(() => actions.saveExpenseAction(form({ id: String(expense.id), category: "Other", amount: "7" })));
    const savedExpense = await prisma.expense.findUniqueOrThrow({ where: { id: expense.id } });
    assert.equal(savedExpense.notes, expense.notes);
    assert.equal(savedExpense.date.getTime(), expense.date.getTime());
    assert.equal(await balance(), 16300);
    await action(() => actions.deleteExpenseAction(form({ id: String(expense.id), cashConfirmed: "yes" })));
    assert.equal(await balance(), 17000);
    await assert.rejects(request(() => actions.cancelSaleAction(form({ id: String(sale.id) }))), /Confirm/);
    await action(() => actions.cancelSaleAction(form({ id: String(sale.id), cashConfirmed: "yes" })));
    assert.equal(await balance(), 7000);
    await action(() => actions.cancelSaleAction(form({ id: String(sale.id), cashConfirmed: "yes" })));
    assert.equal(await balance(), 7000);
    await action(() => actions.cancelPurchaseAction(form({ id: String(purchase.id), cashConfirmed: "yes" })));
    assert.equal(await balance(), 8000);
    await action(() => cashActions.manualCashAction(form({ kind: "OWNER_DEPOSIT", amount: "10", notes: "Float" })));
    assert.equal(await balance(), 9000);
    const session = await prisma.cashSession.findUniqueOrThrow({ where: { openKey: 1 } });
    await assert.rejects(request(() => cashActions.closeCaisseAction(form({ sessionId: String(session.id), counted: "85" }))), /Explain/);
    await action(() => cashActions.closeCaisseAction(form({ sessionId: String(session.id), counted: "85", notes: "Count difference" })));
    assert.equal(await balance(), 8500);
    assert.equal((await prisma.cashSession.findUniqueOrThrow({ where: { id: session.id } })).differenceCents, -500);
    const before = await prisma.expense.count();
    await assert.rejects(request(() => actions.saveExpenseAction(form({ amount: "1" }))), /open a session/);
    assert.equal(await prisma.expense.count(), before);
    await action(cashActions.openCaisseAction);
    assert.equal((await prisma.cashSession.findUniqueOrThrow({ where: { openKey: 1 } })).openingCents, 8500);
    const p = await prisma.payment.findUniqueOrThrow({ where: { ref: "HIST-PAY" } });
    await action(() => actions.voidPaymentAction(form({ id: String(p.id), cashConfirmed: "yes" })));
    assert.equal(await balance(), -1500);
    const open = await prisma.cashSession.findUniqueOrThrow({ where: { openKey: 1 } });
    await prisma.cashSession.update({ where: { id: open.id }, data: { openedAt: new Date(Date.now() - 86400000) } });
    await assert.rejects(request(() => cashActions.manualCashAction(form({ kind: "OWNER_DEPOSIT", amount: "1", notes: "Late" }))), /previous day/);
    console.log("PASS: historical import, idempotency, cash-only validation, deposits, installments, supplier payments, expense corrections, reversals, session closing, carry-forward, stale sessions, and transactional rollback");
  } finally {
    await prisma.$disconnect();
    rmSync(directory, { recursive: true, force: true });
  }
}

main().catch(error => { console.error(error); process.exitCode = 1; });
